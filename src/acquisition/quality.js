/** Per-reading quality flags (bitmask). Persisted with every reading and exported by name. */
export const Q = Object.freeze({
    INVALID: 0x001,          // channel invalid (device valid bit clear, sentinel, non-finite)
    GAP_BEFORE: 0x002,       // one or more sequence numbers missing immediately before this sample
    OUT_OF_ORDER: 0x004,     // arrived after a later sequence number (late arrival)
    DEVICE_OVERRUN: 0x008,   // device reported it missed sample slots before this sample
    BOOT: 0x010,             // device restart / stream epoch start
    HOST_TIME_ONLY: 0x020,   // legacy stream: no device sequence or timestamp
    SIMULATED: 0x040,        // generated by the simulator, not a physical measurement
    SENSOR_FAULT: 0x080,     // device-level sensor fault flag
    TIMEBASE_RESET: 0x100,   // device clock could not be unwrapped unambiguously; new timebase
    SENTINEL: 0x200,         // legacy firmware sentinel value (e.g. 1e6 open circuit)
    CLOCK_ANOMALY: 0x400,    // device time went backwards for a forward sequence step
});

const NAMES = Object.entries(Q).map(([k, v]) => [v, k.toLowerCase()]);

export function flagNames(mask) {
    const out = [];
    for (const [bit, name] of NAMES) if (mask & bit) out.push(name);
    return out;
}

export function flagsFromNames(str) {
    if (!str) return 0;
    let m = 0;
    for (const part of str.split('|')) {
        const e = NAMES.find(([, n]) => n === part);
        if (!e) throw new Error(`unknown quality flag "${part}"`);
        m |= e[0];
    }
    return m;
}

/** Welford running mean/variance with min/max. */
export class RunningStats {
    constructor() { this.reset(); }
    reset() { this.n = 0; this.mean = 0; this.m2 = 0; this.min = Infinity; this.max = -Infinity; }
    push(x) {
        this.n++;
        const d = x - this.mean;
        this.mean += d / this.n;
        this.m2 += d * (x - this.mean);
        if (x < this.min) this.min = x;
        if (x > this.max) this.max = x;
    }
    get std() { return this.n > 1 ? Math.sqrt(this.m2 / (this.n - 1)) : null; }
    toJSON() {
        return this.n === 0
            ? { n: 0, mean: null, std: null, min: null, max: null }
            : { n: this.n, mean: this.mean, std: this.std, min: this.min, max: this.max };
    }
}
