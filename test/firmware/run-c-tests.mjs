/**
 * Compiles firmware/sensorlab_node/sltp.c with the host C compiler and checks it against the
 * shared JSON vectors, demonstrating byte-for-byte agreement with src/protocol/sltp.js.
 * This is a UNIT TEST of serialization, not a test on ESP32 hardware.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const V = JSON.parse(readFileSync(path.join(root, 'test/fixtures/sltp-v1-vectors.json'), 'utf8'));
const outDir = path.join(root, 'build/firmware-test');
mkdirSync(outDir, { recursive: true });

const bytes = (hex) => hex.match(/../g).map(h => '0x' + h).join(',');
const cstr = (s) => JSON.stringify(s);
let h = '/* generated by test/firmware/run-c-tests.mjs — do not edit */\n#include <stdint.h>\n';
h += 'typedef struct { const char *name; uint32_t sequence; uint32_t device_time_us; uint8_t flags; uint8_t channel_count; uint8_t valid_mask; int32_t values[8]; uint8_t bytes[44]; size_t len; } data_vector_t;\n';
h += 'typedef struct { const char *name; uint8_t opcode; uint32_t arg; uint8_t bytes[8]; size_t len; } control_vector_t;\n';
h += 'static const data_vector_t DATA_VECTORS[] = {\n';
for (const v of V.data) {
    const mask = v.valid.reduce((m, ok, i) => m | (ok ? 1 << i : 0), 0);
    const vals = v.values.map(x => (x === -2147483648 ? '(-2147483647 - 1)' : String(x))).join(',');
    h += `  { ${cstr(v.name)}, ${v.sequence}u, ${v.deviceTimeUs}u, ${v.flags}, ${v.values.length}, ${mask}, {${vals}}, {${bytes(v.hex)}}, ${v.hex.length / 2} },\n`;
}
h += '};\n#define DATA_VECTOR_COUNT (sizeof DATA_VECTORS / sizeof DATA_VECTORS[0])\n';
h += 'static const control_vector_t CONTROL_VECTORS[] = {\n';
for (const c of V.control) h += `  { ${cstr(c.name)}, ${c.opcode}, ${c.arg ?? 0}u, {${bytes(c.hex)}}, ${c.hex.length / 2} },\n`;
h += '};\n#define CONTROL_VECTOR_COUNT (sizeof CONTROL_VECTORS / sizeof CONTROL_VECTORS[0])\n';
writeFileSync(path.join(root, 'firmware/test/vectors.h'), h);

const candidates = [process.env.CC, 'gcc', 'cc', 'clang', 'C:/MinGW/bin/gcc.exe'].filter(Boolean);
let cc = null;
let env = process.env;
for (const c of candidates) {
    // An absolute compiler path (e.g. MinGW) needs its own directory on PATH to find cc1/DLLs.
    const e = path.isAbsolute(c) ? { ...process.env, PATH: path.dirname(c) + path.delimiter + process.env.PATH } : process.env;
    const probe = spawnSync(c, ['--version'], { encoding: 'utf8', env: e });
    if (!probe.error && probe.status === 0) { cc = c; env = e; break; }
}
if (!cc) {
    console.error('NOT RUN: no C compiler found (set CC). Firmware serialization is unverified on this machine.');
    process.exit(2);
}
const exe = path.join(outDir, process.platform === 'win32' ? 'test_sltp.exe' : 'test_sltp');
const version = spawnSync(cc, ['--version'], { encoding: 'utf8', env });
console.log(`compiler: ${cc} (${version.stdout.split(/\r?\n/)[0]})`);
const compile = spawnSync(cc, ['-std=c99', '-Wall', '-Wextra', '-Werror', '-pedantic',
    path.join(root, 'firmware/sensorlab_node/sltp.c'), path.join(root, 'firmware/test/test_sltp.c'), '-o', exe], { encoding: 'utf8', env });
if (compile.stdout) process.stdout.write(compile.stdout);
if (compile.stderr) process.stderr.write(compile.stderr);
console.log(`compiler exit code: ${compile.status ?? 'unavailable'}`);
if (compile.error || compile.status !== 0) {
    if (compile.error) console.error(`compiler launch error: ${compile.error.message}`);
    process.exit(compile.error ? 2 : compile.status || 1);
}
const execution = spawnSync(exe, { env });
if (execution.status !== 0 || execution.error) {
    if (execution.stdout?.length) process.stdout.write(execution.stdout.toString('latin1'));
    if (execution.stderr?.length) process.stderr.write(execution.stderr.toString());
}
console.log(`test executable exit code: ${execution.status ?? 'unavailable'}`);
if (execution.error || execution.status !== 0) {
    if (execution.error) console.error(`test executable launch error: ${execution.error.message}`);
    if (execution.signal) console.error(`test executable terminated by signal: ${execution.signal}`);
    process.exit(execution.error ? 2 : execution.status || 1);
}
const out = execution.stdout.toString('latin1');
process.stdout.write(out.split('\n').filter(l => !l.startsWith('INFO_JSON')).join('\n'));
// Contract test: the firmware's INFO JSON must be accepted by the app's real parser (src/protocol/sltp.js).
const { parseDeviceInfo } = await import(pathToFileURL(path.join(root, 'src/protocol/sltp.js')).href);
let contractFail = 0;
for (const line of out.split('\n').filter(l => l.startsWith('INFO_JSON_'))) {
    const tag = line.slice(0, line.indexOf(':'));
    const bytes = Buffer.from(line.slice(line.indexOf(':') + 1).replace(/\r$/, ''), 'latin1'); // raw bytes as emitted by C (UTF-8 inside)
    const r = parseDeviceInfo(new Uint8Array(bytes));
    const ok = r.ok && r.info.channels.length === 2 && r.info.channels[1].unit === 'Ω' && r.info.channels[0].scale === 0.0625 && bytes.length <= 512;
    if (!ok) contractFail++;
    console.log(`${ok ? 'OK' : 'FAIL'}: ${tag} (${bytes.length} bytes) parsed by the app's parseDeviceInfo → ${r.ok ? `serial ${r.info.serial}, period ${r.info.periodUs} µs, units ${r.info.channels.map(c => c.unit).join('/')}` : r.error.code + ' ' + r.error.detail}`);
}
// Documentation contract: the INFO example in docs/PROTOCOL.md §3 must be exactly what the firmware emits (it once said
// "adc_mean" while the firmware sent "adc_sum16").
{
    const doc = readFileSync(path.join(root, 'docs/PROTOCOL.md'), 'utf8');
    const m = doc.match(/## 3\. INFO[\s\S]*?```json\n([\s\S]*?)```/);
    const typical = out.split('\n').find(l => l.startsWith('INFO_JSON_TYPICAL:'));
    const fw = typical ? Buffer.from(typical.slice(typical.indexOf(':') + 1).replace(/\r$/, ''), 'latin1').toString('utf8') : null;
    const docJson = m ? m[1].replace(/\r?\n\s*/g, '') : null;
    const ok = !!fw && docJson === fw;
    if (!ok) contractFail++;
    console.log(`${ok ? 'OK' : 'FAIL'}: docs/PROTOCOL.md INFO example ${ok ? 'equals' : 'differs from'} firmware output${ok ? '' : `\n  doc: ${docJson}\n  fw:  ${fw}`}`);
}
// Regression guard: DEVICE_OVERRUN must describe THIS sample only. A persistent "overrunPending" latch carried the flag onto a
// later packet after a disconnect, so the host attributed an unrelated gap to the device. The sketch must use sltp_advance_slot.
{
    const ino = readFileSync(path.join(root, 'firmware/sensorlab_node/sensorlab_node.ino'), 'utf8');
    const ok = !/overrunPending/.test(ino) && ino.includes('sltp_advance_slot(') && ino.includes('missed > 0 ? SLTP_FLAG_DEVICE_OVERRUN');
    if (!ok) contractFail++;
    console.log(`${ok ? 'OK' : 'FAIL'}: sketch sets DEVICE_OVERRUN per sample from sltp_advance_slot (no persistent latch)`);
}
// Hardware-path contract: the reference sketch must keep the SLTP v1 raw 16-sample aggregate, while using the
// verified XIAO ESP32-C3 D2/A2/GPIO4 input and calibrated 11 dB voltage for the derived resistance channel.
{
    const ino = readFileSync(path.join(root, 'firmware/sensorlab_node/sensorlab_node.ino'), 'utf8');
    const required = [
        '#define SENSOR_PIN      A2',
        'D2 = A2 = GPIO4 = ADC1_CH4',
        '#define ADC_SAMPLES     16',
        'adc_oneshot_config_channel(adcHandle, ADC_CHANNEL_4, &channelCfg)',
        'adc_oneshot_read(adcHandle, ADC_CHANNEL_4, &raw)',
        'adc_cali_raw_to_voltage(adcCaliHandle, raw, &millivolts)',
        'sumMilliVolts += millivolts',
        'divider_measurement_from_mv(',
        's.values[0] = sum',
        'measurement.raw_valid ? 0x01 : 0x00',
        'measurement.resistance_valid ? 0x02 : 0x00',
        'measurement.sensor_fault ? SLTP_FLAG_SENSOR_FAULT : 0',
    ];
    const ok = required.every(s => ino.includes(s)) && !ino.includes('#define SENSOR_PIN      0') && !ino.includes('analogReadMilliVolts(SENSOR_PIN)');
    if (!ok) contractFail++;
    console.log(`${ok ? 'OK' : 'FAIL'}: sketch uses D2/A2/GPIO4, calibrates each raw conversion once, and preserves invalid/fault signalling`);
}
if (contractFail) { console.error(`FIRMWARE↔APP INFO CONTRACT: ${contractFail} failure(s)`); process.exit(1); }
